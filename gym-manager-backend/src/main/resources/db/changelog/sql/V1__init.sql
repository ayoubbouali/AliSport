-- V1 — initial schema (PostgreSQL).
-- Computed values (prices, end dates, remaining days, statuses, salaries, counts)
-- are never stored: they come from com.alisport.gym.rules.Rules.

CREATE TABLE app_settings (
    setting_key   VARCHAR(100) PRIMARY KEY,
    setting_value VARCHAR(2000) NOT NULL
);

-- Next number of each entity code. Never decremented: a code is never reused.
CREATE TABLE code_counters (
    entity     VARCHAR(30) PRIMARY KEY,
    next_value BIGINT NOT NULL
);

CREATE TABLE staff_functions (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label  VARCHAR(80) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE durations (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label  VARCHAR(80) NOT NULL UNIQUE,
    months INTEGER NOT NULL CHECK (months > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE discounts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(20) NOT NULL UNIQUE,
    name             VARCHAR(80) NOT NULL UNIQUE,
    discount_percent NUMERIC(5, 2) NOT NULL CHECK (discount_percent >= 0 AND discount_percent <= 100),
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    system_entry     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE staff (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(20) NOT NULL UNIQUE,
    last_name    VARCHAR(80) NOT NULL,
    first_name   VARCHAR(80) NOT NULL DEFAULT '',
    phone        VARCHAR(30) NOT NULL DEFAULT '',
    function_id  BIGINT NOT NULL REFERENCES staff_functions (id),
    pay_mode     VARCHAR(20) NOT NULL CHECK (pay_mode IN ('COMMISSION', 'FIXED')),
    fixed_salary NUMERIC(12, 2),
    active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sports (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20) NOT NULL UNIQUE,
    name          VARCHAR(80) NOT NULL UNIQUE,
    color         VARCHAR(7) NOT NULL,
    capacity      INTEGER NOT NULL CHECK (capacity >= 0),
    monthly_price NUMERIC(12, 2) NOT NULL CHECK (monthly_price >= 0),
    active        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sport_coaches (
    sport_id BIGINT NOT NULL REFERENCES sports (id) ON DELETE CASCADE,
    staff_id BIGINT NOT NULL REFERENCES staff (id),
    PRIMARY KEY (sport_id, staff_id)
);

CREATE TABLE sport_schedules (
    sport_id    BIGINT NOT NULL REFERENCES sports (id) ON DELETE CASCADE,
    day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  TIME NOT NULL,
    end_time    TIME NOT NULL
);

CREATE TABLE packs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20) NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    sport_id      BIGINT NOT NULL REFERENCES sports (id),
    duration_id   BIGINT NOT NULL REFERENCES durations (id),
    monthly_price NUMERIC(12, 2) NOT NULL CHECK (monthly_price >= 0),
    discount_id   BIGINT NOT NULL REFERENCES discounts (id),
    active        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE members (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(20) NOT NULL UNIQUE,
    last_name         VARCHAR(80) NOT NULL,
    first_name        VARCHAR(80) NOT NULL,
    phone             VARCHAR(30) NOT NULL,
    birth_date        DATE,
    registration_date DATE NOT NULL,
    pack_id           BIGINT NOT NULL REFERENCES packs (id),
    discount_id       BIGINT NOT NULL REFERENCES discounts (id),
    insurance         VARCHAR(10) NOT NULL CHECK (insurance IN ('PAYE', 'IMPAYE')),
    photo             VARCHAR(255),
    notes             VARCHAR(2000) NOT NULL DEFAULT '',
    active            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE member_sports (
    member_id BIGINT NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    sport_id  BIGINT NOT NULL REFERENCES sports (id),
    PRIMARY KEY (member_id, sport_id)
);

CREATE TABLE activities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20) NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    price       NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    starts_at   TIMESTAMP NOT NULL,
    location    VARCHAR(120) NOT NULL DEFAULT '',
    max_places  INTEGER CHECK (max_places IS NULL OR max_places > 0),
    manager_id  BIGINT NOT NULL REFERENCES staff (id),
    active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE activity_registrations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    activity_id BIGINT NOT NULL REFERENCES activities (id),
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT uq_registration UNIQUE (member_id, activity_id)
);

CREATE TABLE app_users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(50) NOT NULL UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,
    role                 VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'ACCUEIL')),
    active               BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_member_sports_sport ON member_sports (sport_id);
CREATE INDEX idx_packs_sport ON packs (sport_id);
CREATE INDEX idx_registrations_activity ON activity_registrations (activity_id);
