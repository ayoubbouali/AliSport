-- V2 — subscription periods (renewals), member payments with numbered receipts, staff payroll.
--
-- A member now has a history of subscription periods. The amount due of a period is frozen
-- when the period is created (accounting: later price changes must not alter past periods).
-- Payment status, balance, end date and remaining days stay computed (Rules).

CREATE TABLE subscriptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    pack_id     BIGINT NOT NULL REFERENCES packs (id),
    discount_id BIGINT NOT NULL REFERENCES discounts (id),
    start_date  DATE NOT NULL,
    months      INTEGER NOT NULL CHECK (months > 0),
    amount      NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    created_at  TIMESTAMP NOT NULL,
    created_by  VARCHAR(50) NOT NULL DEFAULT ''
);
CREATE INDEX idx_subscriptions_member ON subscriptions (member_id);

-- Existing members: their current subscription becomes their first period (price per RG-PRIX).
INSERT INTO subscriptions (member_id, pack_id, discount_id, start_date, months, amount, created_at, created_by)
SELECT m.id, m.pack_id, m.discount_id, m.registration_date, d.months,
       ROUND(CASE WHEN COALESCE((SELECT s.setting_value FROM app_settings s WHERE s.setting_key = 'subscription.cumulative'), 'true') = 'true'
                  THEN p.monthly_price * d.months * (100 - pd.discount_percent) / 100 * (100 - md.discount_percent) / 100
                  ELSE p.monthly_price * d.months * (100 - GREATEST(pd.discount_percent, md.discount_percent)) / 100 END,
             CASE WHEN COALESCE((SELECT s.setting_value FROM app_settings s WHERE s.setting_key = 'subscription.rounding'), '2') = '0' THEN 0 ELSE 2 END),
       CURRENT_TIMESTAMP, 'migration'
FROM members m
JOIN packs p ON p.id = m.pack_id
JOIN durations d ON d.id = p.duration_id
JOIN discounts pd ON pd.id = p.discount_id
JOIN discounts md ON md.id = m.discount_id;

ALTER TABLE members DROP COLUMN pack_id;
ALTER TABLE members DROP COLUMN discount_id;

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number  VARCHAR(30) NOT NULL UNIQUE,
    member_id       BIGINT NOT NULL REFERENCES members (id),
    subscription_id BIGINT NOT NULL REFERENCES subscriptions (id),
    amount          NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method          VARCHAR(20) NOT NULL CHECK (method IN ('ESPECES', 'CARTE', 'VIREMENT')),
    paid_on         DATE NOT NULL,
    note            VARCHAR(500) NOT NULL DEFAULT '',
    created_at      TIMESTAMP NOT NULL,
    created_by      VARCHAR(50) NOT NULL,
    updated_at      TIMESTAMP,
    updated_by      VARCHAR(50),
    cancelled       BOOLEAN NOT NULL DEFAULT FALSE,
    cancelled_at    TIMESTAMP,
    cancelled_by    VARCHAR(50),
    cancel_reason   VARCHAR(500)
);
CREATE INDEX idx_payments_member ON payments (member_id);
CREATE INDEX idx_payments_subscription ON payments (subscription_id);
CREATE INDEX idx_payments_paid_on ON payments (paid_on);

CREATE TABLE salary_payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slip_number   VARCHAR(30) NOT NULL UNIQUE,
    staff_id      BIGINT NOT NULL REFERENCES staff (id),
    period        VARCHAR(7) NOT NULL,           -- YYYY-MM
    amount        NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method        VARCHAR(20) NOT NULL CHECK (method IN ('ESPECES', 'CARTE', 'VIREMENT')),
    paid_on       DATE NOT NULL,
    note          VARCHAR(500) NOT NULL DEFAULT '',
    created_at    TIMESTAMP NOT NULL,
    created_by    VARCHAR(50) NOT NULL,
    cancelled     BOOLEAN NOT NULL DEFAULT FALSE,
    cancelled_at  TIMESTAMP,
    cancelled_by  VARCHAR(50),
    cancel_reason VARCHAR(500)
);
CREATE INDEX idx_salary_payments_staff ON salary_payments (staff_id);
CREATE INDEX idx_salary_payments_period ON salary_payments (period);
